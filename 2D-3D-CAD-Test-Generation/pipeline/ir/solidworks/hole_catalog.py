"""Installed Hole Wizard catalog discovery and resolution (Stage 4, task 4.5).

Two sources, kept apart:

* the **type library** (enum NAMES for standards and fastener types; no COM needed; fixture
  ``tests/fixtures/sw_hole_enums_2025.json`` regenerated by ``tools/read_sw_typelib.py``), and
* the **running catalog** (``ISldWorks.GetHoleStandardsData(general)`` and what it enumerates). This is what proves a
  standard / fastener / size is actually installed. It returns nothing in some sessions (error log E037): that is
  reported as ``HW_CATALOG_ENUMERATION_UNAVAILABLE``, never turned into an empty-but-fine catalog.

``resolve`` maps a selected variant to (standard, fastener type, size). Standard and fastener are looked up by NAME in
the installed enums; a combination the enums do not contain is ``HW_FASTENER_UNMAPPED``. Sizes for clearance and
counterbore holes come from the existing MTI table lookup; for taps from the thread designation. The result says
whether the catalog CONFIRMED the combination (``catalog_confirmed``) or only the type library did; an adapter that
creates from an unconfirmed resolution must rely on readback.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Optional

from pipeline.ir.solidworks.hole_capabilities import Variant
from pipeline.ir.solidworks.hole_intent import HoleIntent

_FIXTURE = Path(__file__).resolve().parents[3] / "tests" / "fixtures" / "sw_hole_enums_2025.json"

# Fastener-type name suffix per family (after "swStandard<Std>"). Slot families are NOT mapped: the documentation set
# available here does not say which fastener type a slot uses, and a guess would violate "never invent".
FASTENER_SUFFIX = {
    "hole": ("ScrewClearances",),
    "counterbore": ("SocketCapScrew", "SocketHeadCapScrew"),
    "countersink": ("FlatSocket82", "FlatHead82", "FlatHead100", "FlatHead90"),
    "straight_tap": ("TappedHole",),
    "pipe_tap": ("TaperedPipeTap",),
}
SYSTEM_STANDARD = {"inch": "AnsiInch", "metric": "AnsiMetric", "mm": "AnsiMetric"}


@dataclass
class EnumTable:
    standards: dict          # name -> value  (swStandard...)
    fasteners: dict          # name -> value  (swStandard...<type>)

    @classmethod
    def installed(cls, path: Optional[Path] = None) -> "EnumTable":
        s = json.loads((path or _FIXTURE).read_text(encoding="utf-8"))
        return cls(dict(s["swWzdHoleStandards_e"]), dict(s["swWzdHoleStandardFastenerTypes_e"]))


@dataclass
class CatalogSnapshot:
    available: bool
    code: Optional[str] = None
    detail: str = ""
    families: dict = field(default_factory=dict)     # general -> {"standards": [...], "fasteners": {std: [...]}}


def discover(app: Any, generals=range(9)) -> CatalogSnapshot:
    """Enumerate the running catalog. Any failure (an exception, ``False``, empty arrays) is
    ``HW_CATALOG_ENUMERATION_UNAVAILABLE`` with the detail, never an empty catalog treated as complete."""
    fams: dict = {}
    problems = []
    for g in generals:
        if g == 5:
            continue                                   # legacy has no standards data
        try:
            data = app.GetHoleStandardsData(g)
            if data is None:
                problems.append(f"general {g}: no standards object")
                continue
            res = data.GetHoleStandards()
            ok, arr = (res if isinstance(res, tuple) and len(res) == 2 and isinstance(res[0], bool) else (bool(res), res))
            arr = list(arr) if arr and not isinstance(arr, (bool, int)) else []
            if not ok or not arr:
                problems.append(f"general {g}: GetHoleStandards returned no standards")
                continue
            fams[g] = {"standards": arr, "fasteners": {}}
        except Exception as e:  # COM errors are varied; the code is what matters
            problems.append(f"general {g}: {type(e).__name__}: {str(e)[:80]}")
    if not fams:
        return CatalogSnapshot(False, "HW_CATALOG_ENUMERATION_UNAVAILABLE", "; ".join(problems) or "nothing enumerated")
    return CatalogSnapshot(True, None, "; ".join(problems), fams)


@dataclass
class Resolution:
    variant: Variant
    general: int
    standard: Optional[int] = None
    standard_name: str = ""
    fastener: Optional[int] = None
    fastener_name: str = ""
    size: str = ""
    catalog_confirmed: bool = False
    code: Optional[str] = None            # None = resolved
    reason: str = ""
    warnings: list = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return self.code is None


def _standard_name(intent: HoleIntent) -> Optional[str]:
    if intent.standard:
        return intent.standard
    sys = (intent.thread or {}).get("system") if intent.thread else None
    return SYSTEM_STANDARD.get(sys or intent.units)


def _size(intent: HoleIntent, variant: Variant) -> tuple[str, Optional[str]]:
    """The size string SolidWorks expects, or (``""``, reason)."""
    from pipeline.ir.compile_solidworks import parse_thread
    if variant.family in ("straight_tap", "pipe_tap"):
        th = intent.thread or {}
        des = th.get("designation") or th.get("size") or ""
        if variant.family == "pipe_tap":
            if not th.get("standard"):
                return "", "pipe thread standard is not stated (NPT/NPTF/BSPT are never inferred from a diameter)"
            return str(th.get("size") or des), None
        p = parse_thread(des)
        if p is None:
            return "", f"thread {des!r} is not a size SolidWorks names"
        return p[1], None
    from pipeline import mti_standards
    if intent.diameter is None:
        return "", "no diameter to size from"
    match = mti_standards.match_hole(intent.diameter, intent.units, ("clearance_normal", "clearance_loose"))
    if not match:
        return "", f"diameter {intent.diameter} {intent.units} matches no clearance size"
    return match[0].size, None


def resolve(intent: HoleIntent, variant: Variant, table: Optional[EnumTable] = None,
            snapshot: Optional[CatalogSnapshot] = None) -> Resolution:
    t = table or EnumTable.installed()
    r = Resolution(variant, variant.general)
    if variant.family not in FASTENER_SUFFIX:
        r.code, r.reason = "HW_FASTENER_UNMAPPED", f"{variant.family}: no fastener type is documented for this family; needs catalog discovery"
        return r
    sname = _standard_name(intent)
    if not sname or f"swStandard{sname}" not in t.standards:
        r.code, r.reason = "HW_STANDARD_UNKNOWN", f"standard {sname!r} is not in the installed swWzdHoleStandards_e"
        return r
    r.standard_name, r.standard = f"swStandard{sname}", t.standards[f"swStandard{sname}"]
    for suf in FASTENER_SUFFIX[variant.family]:
        if variant.family == "countersink" and intent.csink_angle is not None and not any(
                str(int(intent.csink_angle)) in s for s in (suf,)):
            continue
        n = f"swStandard{sname}{suf}"
        if n in t.fasteners:
            r.fastener_name, r.fastener = n, t.fasteners[n]
            break
    if r.fastener is None:
        r.code, r.reason = "HW_FASTENER_UNMAPPED", f"no installed fastener type for {variant.family} under swStandard{sname}"
        return r
    size, why = _size(intent, variant)
    if why:
        r.code, r.reason = "HW_SIZE_UNRESOLVED", why
        return r
    r.size = size
    if snapshot is None or not snapshot.available:
        r.warnings.append(snapshot.code if snapshot is not None and snapshot.code else "HW_CATALOG_NOT_CONSULTED")
    else:
        fam = snapshot.families.get(variant.general, {})
        r.catalog_confirmed = bool(fam) and r.standard in [int(s) if str(s).lstrip("-").isdigit() else s for s in fam["standards"]]
        if not r.catalog_confirmed:
            r.code, r.reason = "HW_CATALOG_MISSING", f"{r.standard_name} is not installed for general type {variant.general}"
    return r
