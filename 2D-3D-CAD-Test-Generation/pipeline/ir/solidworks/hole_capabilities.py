@dataclass(frozen=True)
class Variant:
    value: int
    name: str
    general: int
    family: str
    end: Optional[str]                  # "blind" | "through" | None (legacy: carried by the legacy definition)
    treatments: tuple = ()              # subset of near / middle / far (countersink treatments)
    thread: Optional[str] = None        # None | "plain" | "cosmetic" | "thread_through" | "remove"
    head_clearance: Optional[bool] = None   # False for the "WithoutHeadClearance" variants
    legacy: bool = False
    property_groups: tuple = ()
    required_intent: tuple = ()
    status: str = "not_implemented"

    @property
    def properties(self) -> tuple:
        return tuple(dict.fromkeys(p for g in self.property_groups for p in PROPERTY_GROUPS[g]))


def _classify(value: int, name: str) -> Variant:
    if value in LEGACY_VALUES:
        return Variant(value, name, 5, "legacy", None, legacy=True, property_groups=("identity", "bore", "scope"),
                       required_intent=REQUIRED_INTENT["legacy"])
    rest = name[2:]
    general = None
    for pref, g in _PREFIX:
        if rest.lower().startswith(pref.lower()):
            general, rest = g, rest[len(pref):]
            break
    if general is None:
        raise ValueError(f"cannot classify {name}")
    m = re.match(r"(Blind|Thru)", rest, re.I)
    if not m:
        raise ValueError(f"no end condition in {name}")
    end = "blind" if m.group(1).lower() == "blind" else "through"
    rest = rest[m.end():]
    thread = None
    if general in (3, 4):
        thread = "plain"
        for key, val in (("CosmeticThread", "cosmetic"), ("ThreadThru", "thread_through"), ("RemoveThread", "remove")):
            if rest.lower().startswith(key.lower()):
                thread, rest = val, rest[len(key):]
                break
    no_head = "withoutheadclearance" in rest.lower()
    rest = re.sub(r"withoutheadclearance", "", rest, flags=re.I)
    treatments: tuple = ()
    if re.match(r"counter\s*sink", rest, re.I):
        treatments = tuple(_SIDE[t.lower()] for t in re.findall(r"top|middle|bottom", rest, re.I))
    family = GENERAL_FAMILIES[general]
    groups = ["identity", "bore", "scope"]
    if general in (0, 6):
        groups.append("counterbore")
    if general in (1, 7) or "near" in treatments or "middle" in treatments or "far" in treatments:
        groups.append("countersink")
    if "near" in treatments:
        groups.append("near")
    if "middle" in treatments:
        groups.append("middle")
    if "far" in treatments:
        groups.append("far")
    if general in (3, 4):
        groups.append("thread")
    if general in (6, 7, 8):
        groups.append("slot")
    head = False if no_head else (True if general in (1, 7) else None)
    return Variant(value, name, general, family, end, treatments, thread, head, False, tuple(dict.fromkeys(groups)),
                   REQUIRED_INTENT[family])


VARIANTS: dict[int, Variant] = {v: _classify(v, n) for v, n in SPECIFIC.items()}
BY_NAME = {v.name: v for v in VARIANTS.values()}


def classify(value: int) -> dict:
    """The registry entry for an enum value, or an explicit ``unknown_variant`` result (fail closed)."""
    v = VARIANTS.get(value)
    if v is None:
        return {"known": False, "value": value, "status": "not_implemented", "reason": "unknown_variant",
                "action": "classify this swWzdHoleTypes_e member from the installed type library before use"}
    return {"known": True, "variant": v, "status": v.status}


def unknown_members(live_enum: dict) -> dict:
    """Members of the installed enum that the registry does not know, and members it expects that are missing."""
    live = {int(k): n for k, n in live_enum.items()} if live_enum and isinstance(next(iter(live_enum)), str) and str(next(iter(live_enum))).lstrip("-").isdigit() \
        else {int(v): k for k, v in live_enum.items()}
    return {"unknown_to_registry": {v: n for v, n in live.items() if v not in SPECIFIC},
            "missing_in_install": {v: n for v, n in SPECIFIC.items() if v not in live},
            "renamed": {v: (SPECIFIC[v], n) for v, n in live.items() if v in SPECIFIC and SPECIFIC[v] != n}}


def family_counts() -> dict:
    out: dict = {}
    for v in VARIANTS.values():
        out[v.family] = out.get(v.family, 0) + 1
    return out


def fail_closed_rows(live_enum: dict) -> list:
    """One report row per member of the INSTALLED enum the registry does not know (a future release). Each is
    ``UNSUPPORTED_WITH_REASON``/``unknown_variant`` and is never attempted."""
    drift = unknown_members(live_enum)
    return [{"value": v, "name": n, "status": "not_implemented", "status_2025": "UNSUPPORTED_WITH_REASON", "reason": "unknown_variant",
             "action": "classify this swWzdHoleTypes_e member from the installed type library before use"}
            for v, n in sorted(drift["unknown_to_registry"].items())]
