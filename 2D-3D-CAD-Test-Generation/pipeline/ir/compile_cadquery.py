"""BuildPlan -> deterministic CadQuery script -> reference STEP + feature map (IR v2, Task 4).

``emit_script`` evaluates every plan expression against the drawing's dimensions and
writes one call per feature on :class:`pipeline.ir.cq_runtime.Model`. Each value is
followed by a comment naming the expression it came from, so the script reads as a
traceable build sheet. No timestamps or paths, so golden tests compare it as text.

``build`` runs the same plan in-process (tests). ``run_script`` runs an emitted script
in a subprocess with a timeout (production: an OCC crash can't take down the pipeline).
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional

from pipeline.ir.expr import evaluate
from pipeline.ir.model import (
    BuildPlan, EdgeOp, Hole, Pattern, Prism, Revolve, resolve_edge_query, resolve_ref,
)

CODE_ROOT = Path(__file__).resolve().parent.parent.parent


@dataclass
class CadQueryResult:
    script: str
    feature_map: dict[str, Any]
    step_path: Optional[Path]
    model: Any = None  # the runtime Model (in-process builds only)


def _num(expr, dims: dict[str, float]) -> float:
    return round(evaluate(expr, dims).value, 9)


def _fmt(v: float) -> str:
    s = repr(float(v))
    return s[:-2] if s.endswith(".0") else s


def _profile(p, dims) -> tuple[str, str]:
    """(python dict literal, comment) for a profile."""
    fields = [n for n in type(p).model_fields if n != "shape"]
    vals, notes = [f"'shape': '{p.shape}'"], []
    for n in fields:
        x = getattr(p, n)
        if n == "anchor":
            vals.append(f"'anchor': '{x}'")
        elif n == "points":
            pts = [(_num(a, dims), _num(b, dims)) for a, b in x]
            vals.append("'points': [" + ", ".join(f"({_fmt(a)}, {_fmt(b)})" for a, b in pts) + "]")
            notes.append("points=" + " ".join(f"({a},{b})" for a, b in x))
        else:
            vals.append(f"'{n}': {_fmt(_num(x, dims))}")
            notes.append(f"{n}={x}")
    return "{" + ", ".join(vals) + "}", ", ".join(notes)


def _seed_op(plan: BuildPlan, seed: str) -> str:
    f = plan.feature(seed)
    if isinstance(f, Hole):
        return "cut"
    if isinstance(f, (Prism, Revolve)):
        return f.op
    if isinstance(f, Pattern):
        return _seed_op(plan, f.seed)
    return "add"


def emit_script(plan: BuildPlan, dims: dict[str, float], strict: bool = True) -> str:
    L = [
        f"# {plan.part}: CadQuery reference generated from BuildPlan IR {plan.ir_version}.",
        "# Generated by pipeline.ir.compile_cadquery. Do not edit; change the plan.",
        "# Values are evaluated plan expressions; each '# ...' names its source dimensions.",
        "import sys",
        "from pipeline.ir.cq_runtime import Model",
        "",
        f"m = Model({plan.part!r}, origin_kind={plan.frame.origin_kind!r}, units={plan.frame.units!r}"
        + ("" if strict else ", strict=False") + ")",
    ]
    for f in plan.features:
        if f.status != "planned":
            L.append(f"m.skip({f.id!r}, {f'{f.status}: {f.rationale}'[:200]!r})")
            continue
        if isinstance(f, Prism):
            prof, note = _profile(f.profile, dims)
            depth = "'thru'" if f.depth == "thru" else _fmt(_num(f.depth, dims))
            L.append(f"m.prism({f.id!r}, on={resolve_ref(f.on, dims)!r}, offset={_fmt(_num(f.offset, dims))}, "
                     f"profile={prof}, depth={depth}, op={f.op!r})"
                     f"  # {note}; depth={f.depth}; offset={f.offset}")
        elif isinstance(f, Revolve):
            def stations(items):
                return "[" + ", ".join(f"({_fmt(_num(s.z, dims))}, {_fmt(_num(s.r, dims))})" for s in items) + "]"

            src = "outer " + " ".join(f"({s.z},{s.r})" for s in f.outer)
            if f.inner:
                src += "; inner " + " ".join(f"({s.z},{s.r})" for s in f.inner)
            L.append(f"m.revolve({f.id!r}, outer={stations(f.outer)}, inner={stations(f.inner)}, "
                     f"op={f.op!r})  # {src}")
        elif isinstance(f, Hole):
            s = f.spec
            spec = {"type": s.type, "d": _num(s.d, dims)}
            for n in ("depth", "cbore_d", "cbore_depth", "csink_d", "csink_angle"):
                if getattr(s, n) is not None:
                    spec[n] = _num(getattr(s, n), dims)
            body = ", ".join(f"'{k}': {v!r}" if isinstance(v, str) else f"'{k}': {_fmt(v)}" for k, v in spec.items())
            L.append(f"m.hole({f.id!r}, on={resolve_ref(f.on, dims)!r}, u={_fmt(_num(f.u, dims))}, v={_fmt(_num(f.v, dims))}, "
                     f"spec={{{body}}})  # u={f.u}, v={f.v}, d={s.d}"
                     + (f", cbore={s.cbore_d}x{s.cbore_depth}" if s.cbore_d else ""))
        elif isinstance(f, Pattern):
            step = "'equal'" if f.step == "equal" else _fmt(_num(f.step, dims))
            L.append(f"m.pattern({f.id!r}, seed={f.seed!r}, mode={f.mode!r}, "
                     f"count={int(round(_num(f.count, dims)))}, pitch={_fmt(_num(f.pitch, dims))}, dir={f.dir!r}, "
                     f"count2={int(round(_num(f.count2, dims)))}, pitch2={_fmt(_num(f.pitch2, dims))}, dir2={f.dir2!r}, "
                     f"axis={f.axis!r}, step={step}, skip={f.skip!r}, op={_seed_op(plan, f.seed)!r})"
                     f"  # count={f.count}, pitch={f.pitch}")
        elif isinstance(f, EdgeOp):
            L.append(f"m.{'edge_op'}({f.id!r}, operation={f.operation!r}, size={_fmt(_num(f.size, dims))}, "
                     f"angle={_fmt(_num(f.angle, dims))}, edges={[resolve_edge_query(q, dims) for q in f.edges]!r})"
                     f"  # size={f.size}; edges={f.edges}")
    L += ["", "fmap = m.finish(sys.argv[1] if len(sys.argv) > 1 else None)", ""]
    return "\n".join(L)


def build(plan: BuildPlan, dims: dict[str, float], out_dir: Optional[Path] = None,
          strict: bool = True) -> CadQueryResult:
    """Emit the script and execute it in-process (tests, quick checks)."""
    script = emit_script(plan, dims, strict)
    ns: dict[str, Any] = {"__name__": "__ir_build__"}
    argv = sys.argv
    sys.argv = ["ir_build"] + ([str(out_dir)] if out_dir else [])
    try:
        exec(compile(script, f"<{plan.part} plan>", "exec"), ns)  # noqa: S102 - our own emitted script
    finally:
        sys.argv = argv
    return CadQueryResult(script, ns["fmap"], (out_dir / "reference.step") if out_dir else None, ns["m"])


def run_script(script: str, out_dir: Path, timeout: float = 300.0) -> CadQueryResult:
    """Run an emitted script in a subprocess; returns the feature map it wrote."""
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "reference_script.py"
    path.write_text(script, encoding="utf-8")
    env = {**os.environ, "PYTHONPATH": str(CODE_ROOT), "PYTHONUTF8": "1"}
    proc = subprocess.run([sys.executable, str(path), str(out_dir)], capture_output=True, text=True,
                          timeout=timeout, env=env)
    if proc.returncode != 0:
        raise RuntimeError(f"CadQuery script failed:\n{proc.stderr[-2000:]}")
    fmap = json.loads((out_dir / "feature_map.json").read_text(encoding="utf-8"))
    return CadQueryResult(script, fmap, out_dir / "reference.step")
