"""Inventory hole/thread callouts in the repo's own saved runs and report how well the parser reads them (Stage 4, 4.2).

Reads only local files (no network, no model call): ``plan.json`` ``source_callouts`` (raw callout text) and the
structured ``hole_callouts`` of ``*_extraction.json``. Writes a sanitized report: only text the parser classifies
as a hole/thread callout is quoted, never general notes.

    python tools/inventory_hole_callouts.py --root .. --out ../docs/hole-wizard/callout-inventory.md
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from pipeline.hole_callouts import parse  # noqa: E402

PIPE = re.compile(r"\b(NPTF|NPT|BSPT|BSPP)\b", re.I)


def _json(p: Path):
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def collect(root: Path) -> dict:
    callouts: dict[str, set] = {}      # text -> part ids
    structured = Counter()
    thread_specs = Counter()
    parts_with_holes = set()
    for p in sorted(root.rglob("plan.json")):
        d = _json(p) or {}
        feats = (d.get("plan") or {}).get("features") or []
        part = p.parent.name
        for f in feats:
            if isinstance(f, dict) and f.get("kind") in ("hole", "pattern"):
                for c in f.get("source_callouts") or []:
                    if isinstance(c, str) and c.strip():
                        callouts.setdefault(c.strip(), set()).add(part)
    for p in sorted(root.rglob("*_extraction.json")):
        d = _json(p) or {}
        for h in d.get("hole_callouts") or []:
            if isinstance(h, dict):
                structured[str(h.get("type") or "unknown")] += 1
                parts_with_holes.add(p.parent.name)
                ts = str(h.get("thread_spec") or "").strip()
                if ts:
                    thread_specs["pipe" if PIPE.search(ts) else "straight"] += 1
                    callouts.setdefault(ts, set()).add(p.parent.name)
    return {"callouts": callouts, "structured": structured, "thread_specs": thread_specs, "parts": parts_with_holes}


def classify(callouts: dict) -> dict:
    rows, fam, status = [], Counter(), Counter()
    for text, parts in sorted(callouts.items()):
        r = parse(text)
        st = "not_a_hole_callout" if r.family is None else ("parsed_with_ambiguity" if r.ambiguities else "parsed")
        status[st] += 1
        if r.family:
            fam[r.family] += 1
        rows.append({"text": text, "parts": sorted(parts), "family": r.family, "status": st, "ambiguities": r.ambiguities,
                     "confidence": r.confidence})
    return {"rows": rows, "family": fam, "status": status}


def render(info: dict, res: dict) -> str:
    L = ["# Hole callout inventory (Stage 4, task 4.2)", "",
         "Generated by `tools/inventory_hole_callouts.py` from this repository's saved runs. Local files only; nothing was sent anywhere.",
         "Only callouts the parser classifies as hole/thread text are quoted below; other notes are counted, not shown.", "",
         f"* Distinct callout strings scanned: **{len(res['rows'])}**",
         f"* Parts with extracted hole callouts: **{len(info['parts'])}**",
         "* Structured extraction types: " + (", ".join(f"{k}={v}" for k, v in info["structured"].most_common()) or "none"),
         "* Structured thread specs: " + (", ".join(f"{k}={v}" for k, v in info["thread_specs"].most_common()) or "none"), "",
         "## Parser coverage", "", "| Status | Count |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in res["status"].most_common()]
    L += ["", "## Families the parser assigns", "", "| Family | Count |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in res["family"].most_common()]
    amb = Counter(a for r in res["rows"] for a in r["ambiguities"])
    L += ["", "## Ambiguities raised (never guessed)", "", "| Ambiguity | Count |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in amb.most_common()] or ["| none | 0 |"]
    L += ["", "## Hole/thread callouts and how they parsed", "", "| Callout | Parts | Family | Status | Ambiguities |", "|---|---|---|---|---|"]
    for r in res["rows"]:
        if r["family"]:
            L.append(f"| `{r['text'][:70]}` | {', '.join(r['parts'][:3])}{'…' if len(r['parts']) > 3 else ''} | {r['family']} | {r['status']} | {', '.join(r['ambiguities']) or '-'} |")
    missed = [r for r in res["rows"] if r["family"] is None and re.search(r"\b(THRU|DEEP|DIA|TAP|THD|UNC|UNF|NPT|M\d)\b|\u00d8", r["text"], re.I)]
    L += ["", "## Strings that look like hole text but did NOT parse (parser gaps to review)", ""]
    L += [f"* `{r['text'][:90]}` ({', '.join(r['parts'][:2])})" for r in missed[:40]] or ["* none"]
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=Path(".."))
    ap.add_argument("--out", type=Path, default=Path("../docs/hole-wizard/callout-inventory.md"))
    a = ap.parse_args()
    info = collect(a.root)
    res = classify(info["callouts"])
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(render(info, res), encoding="utf-8")
    print(json.dumps({"strings": len(res["rows"]), "status": dict(res["status"]), "family": dict(res["family"])}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
