"""Writes the v8 comparison / cost fixture jobs into an ISOLATED data dir (never the real one): python make_v8_fixture.py <data_dir> [reset]

Builds everything make_v7_fixture.py builds (jobs r3d_70...01..03), then adds one more job with hand-made, clearly labelled stand-ins:

  r3d_8000000000000001   (all parts: match mode unless noted; every PDF is generated by hand from tests/server/reverse_fixtures.tiny_pdf, NOT SOLIDWORKS output)
    verified      completed, 1-page source and 1-page generated are the SAME bytes (so the in-browser difference must report 0 differing pixels)
    needsrev      review_required, different source / generated text, backend overlay + difference + side-by-side PNGs, issues R001..R004
    multi         completed, 2-page source and 2-page generated (page selection, sync)
    mismatchpages review_required, 2-page source vs 1-page generated (sync not offered)
    blocked       failed (reference blocked, no files)
    plain         completed, Standard mode (no source, no comparison)
    nosld         completed, match, PDF but no SLDDRW (editable output unavailable)

The job/part JSON is the real stored shape. The v8 fields (replication, usage, timing, estimate) are NOT stored by this seed: the backend computes them from its own
ledger, so the browser spec injects realistic V8_CONTRACT.md shapes into GET /api/reverse/jobs/<id> responses (tests/e2e/helpers/v8data.ts). They prove only the UI's
handling of such payloads, not backend output.
"""
import json
