T = "2026-11-27T12:00:00+00:00"
JOB = "r3d_8000000000000001"


def png(w: int, h: int, paint) -> bytes:
    """A real RGB PNG (stdlib only); paint(x, y) -> (r, g, b)."""
    rows = bytearray()
    for y in range(h):
        rows.append(0)
        for x in range(w):
            rows += bytes(paint(x, y))

    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(bytes(rows))) + chunk(b"IEND", b"")


def overlay_png():
    return png(306, 210, lambda x, y: (255, 0, 0) if 60 < x < 140 and 80 < y < 100 else ((0, 0, 255) if 160 < x < 240 and 80 < y < 100 else (250, 250, 250)))


def diff_png():
    return png(306, 210, lambda x, y: (235, 60, 60) if 60 < x < 140 and 80 < y < 100 else (255, 255, 255))


def sbs_png():
    return png(306, 210, lambda x, y: (40, 110, 255) if x < 153 and y % 40 < 3 else (240, 240, 240))


def set_pdf(jd: Path, part: state.PartState, name: str, data: bytes) -> None:
    f = jd / part.part_id / "active" / name
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_bytes(data)
    key = {"drawing.pdf": "drawing.pdf", "reference/source.pdf": "reference/source.pdf"}.get(name, name)
    part.artifacts[key] = f"{part.part_id}/active/{name}"


def add_images(jd: Path, part: state.PartState, kinds=("side_by_side", "overlay", "diff")) -> None:
    mk = {"side_by_side": sbs_png, "overlay": overlay_png, "diff": diff_png}
    for k in kinds:
        f = jd / part.part_id / "active" / "comparison" / f"{k}-page-001.png"
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_bytes(mk[k]())
        part.artifacts[f"comparison/{k}-page-001.png"] = f"{part.part_id}/active/comparison/{k}-page-001.png"


def stage_done(part: state.PartState, na=()) -> None:
    part.stages = v7.stages(10, na=na)


def match_ref(part: state.PartState, name: str, pages: int, cache: str, usd=None) -> None:
    part.reference = {"mode": "match", "status": "resolved", "source_kind": "upload", "filename": name, "sha256": "ab" * 32, "pages": pages, "extraction_cache": cache,
                      "api_usage": {"tokens": 0, "usd": usd if usd is not None else 0.0, "calls": 0 if cache == "hit" else 2, "incremental": True}, "warnings": []}


def build(data: Path) -> None:
    v7.build(data)
    store = state.JobStore(data / "outputs" / "3d-to-2d")
    job = fx.write_job(data, JOB, [("verified.SLDPRT", "completed"), ("needsrev.SLDPRT", "review"), ("multi.SLDPRT", "completed"), ("mismatchpages.SLDPRT", "review"),
                                   ("blocked.SLDPRT", "failed"), ("plain.SLDPRT", "completed"), ("nosld.SLDPRT", "completed")], created=T)
    jd = store.dir(JOB)
    P = {p.part_id: p for p in job.parts}
    for pid in ("verified", "needsrev", "multi", "mismatchpages", "plain", "nosld"):
        stage_done(P[pid])
    # verified: identical source and generated bytes
    same = fx.tiny_pdf(label="VERIFIED SHEET R12", pages=1)
    set_pdf(jd, P["verified"], "drawing.pdf", same)
    set_pdf(jd, P["verified"], "reference/source.pdf", same)
    match_ref(P["verified"], "verified-original.pdf", 1, "hit")
    P["verified"].verification = {"status": "passed", "coverage": {"matched": 9, "total": 9, "unresolved": []}, "iterations": {"used": 1, "max": 3}}
    # needsrev: different text, backend images
    set_pdf(jd, P["needsrev"], "drawing.pdf", fx.tiny_pdf(label="GENERATED NOTE 9", pages=1))
    set_pdf(jd, P["needsrev"], "reference/source.pdf", fx.tiny_pdf(label="ORIGINAL R12 TYP DIM", pages=1))
    add_images(jd, P["needsrev"])
    match_ref(P["needsrev"], "needsrev-original.pdf", 1, "supplemented", 0.0317)
    P["needsrev"].verification = {"status": "review_required", "coverage": {"matched": 7, "total": 9, "unresolved": []}, "iterations": {"used": 3, "max": 3}}
    # multi: two pages both sides
    set_pdf(jd, P["multi"], "drawing.pdf", fx.tiny_pdf(label="MULTI GENERATED", pages=2))
    set_pdf(jd, P["multi"], "reference/source.pdf", fx.tiny_pdf(label="MULTI SOURCE", pages=2))
    match_ref(P["multi"], "multi-original.pdf", 2, "fresh", 0.0043)
    P["multi"].verification = {"status": "passed", "coverage": {"matched": 20, "total": 20, "unresolved": []}}
    # mismatchpages: 2 source pages vs 1 generated
    set_pdf(jd, P["mismatchpages"], "drawing.pdf", fx.tiny_pdf(label="ONE SHEET", pages=1))
    set_pdf(jd, P["mismatchpages"], "reference/source.pdf", fx.tiny_pdf(label="TWO SHEETS", pages=2))
    match_ref(P["mismatchpages"], "mismatch-original.pdf", 2, "fresh")
    P["mismatchpages"].verification = {"status": "review_required", "coverage": {"matched": 3, "total": 8, "unresolved": []}}
    # blocked
    P["blocked"].error = "REFERENCE_BLOCKED: no reference could be resolved for this part"
    P["blocked"].reference = {"mode": "match", "status": "blocked", "source_kind": "none", "warnings": []}
    P["blocked"].verification = {"status": "not_run"}
    P["blocked"].stages = v7.stages(3, failed="reference_resolution")
    # plain: Standard, no source
    P["plain"].reference = {"mode": "standard", "status": "not_applicable", "source_kind": "none", "warnings": []}
    P["plain"].verification = {"status": "passed", "coverage": {"matched": 5, "total": 5, "unresolved": []}}
    # nosld: PDF but no editable drawing
    set_pdf(jd, P["nosld"], "drawing.pdf", fx.tiny_pdf(label="NO SLDDRW", pages=1))
    set_pdf(jd, P["nosld"], "reference/source.pdf", fx.tiny_pdf(label="NO SLDDRW SOURCE", pages=1))
    v7.drop_artifact(jd, P["nosld"], "drawing.slddrw")
    match_ref(P["nosld"], "nosld-original.pdf", 1, "fresh")
    P["nosld"].verification = {"status": "passed", "coverage": {"matched": 4, "total": 4, "unresolved": []}}
    for p in job.parts:
        p.artifacts = {k: v for k, v in p.artifacts.items() if (jd / v).is_file()}
    store.save(job)
    (data / "V8_SEED.json").write_text(json.dumps({"job": JOB, "note": "TEST SEED. PDFs are hand-made stand-ins (tiny_pdf). The v8 fields are injected by the browser spec."}, indent=2), encoding="utf-8")


def main() -> int:
    data = Path(sys.argv[1])
    if len(sys.argv) > 2 and sys.argv[2] == "reset":
        shutil.rmtree(data / "outputs" / "3d-to-2d", ignore_errors=True)
    build(data)
    print("ok v8 fixture")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
