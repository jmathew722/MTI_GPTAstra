def box_stl(sx=40.0, sy=25.0, sz=10.0) -> bytes:
    """A binary STL cuboid (12 triangles), millimetres."""
    v = [(0, 0, 0), (sx, 0, 0), (sx, sy, 0), (0, sy, 0), (0, 0, sz), (sx, 0, sz), (sx, sy, sz), (0, sy, sz)]
    f = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4), (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
    out = bytearray(b"TEST FIXTURE box - not a SOLIDWORKS export".ljust(80, b" ")) + struct.pack("<I", len(f))
    for a, b, c in f:
        out += struct.pack("<3f", 0, 0, 0)
        for i in (a, b, c):
            out += struct.pack("<3f", *v[i])
        out += b"\0\0"
    return bytes(out)


def tiny_pdf(label: str = "TEST FIXTURE - not a SOLIDWORKS drawing", pages: int = 1) -> bytes:
    """A valid white-paper PDF with a border and a label (generated by hand; no library)."""
    objs: list[bytes] = []
    kids = " ".join(f"{3 + 2 * i} 0 R" for i in range(pages))
    objs.append(b"<< /Type /Catalog /Pages 2 0 R >>")
    objs.append(f"<< /Type /Pages /Kids [{kids}] /Count {pages} >>".encode())
    for i in range(pages):
        content = (f"1 w 30 30 540 360 re S BT /F1 14 Tf 60 360 Td ({label} - sheet {i + 1}) Tj ET 0.5 w 150 150 m 450 150 l 450 300 l 150 300 l h S").encode()
        objs.append(f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 420] /Contents {4 + 2 * i} 0 R /Resources << /Font << /F1 {3 + 2 * pages + 0} 0 R >> >> >>".encode())
        objs.append(b"<< /Length %d >>\nstream\n" % len(content) + content + b"\nendstream")
    objs.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    out = bytearray(b"%PDF-1.4\n")
    offs = []
    for n, o in enumerate(objs, 1):
        offs.append(len(out))
        out += f"{n} 0 obj\n".encode() + o + b"\nendobj\n"
    x = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    for o in offs:
        out += f"{o:010d} 00000 n \n".encode()
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{x}\n%%EOF\n".encode()
    return bytes(out)


def tiny_png(w=160, h=110) -> bytes:
    """A white PNG with a dark border (stdlib only)."""
    rows = bytearray()
    for y in range(h):
        rows.append(0)
        for x in range(w):
            rows += b"\x30\x30\x30" if (x in (0, w - 1) or y in (0, h - 1)) else b"\xf7\xf7\xf5"
    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(bytes(rows))) + chunk(b"IEND", b"")


