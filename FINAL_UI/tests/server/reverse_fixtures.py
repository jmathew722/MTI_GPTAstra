def make_part(job: state.Job, name: str, kind: str, job_dir: Path) -> state.PartState:
    """kind: completed | review | processing | failed | queued | canceled | stl_only"""
    pid = name.rsplit(".", 1)[0]
    p = state.PartState(part_id=pid, source="(fixture)", name=name)
    t = "2026-11-25T10:00:00+00:00"
    def stages_to(n, running=None):
        for i, s in enumerate(STAGE_ORDER[:n]):
            p.stages[s] = {"status": "succeeded", "started": t, "ended": t, "warnings": [], "errors": [], "seconds": 4.0 + i}
        if running:
            p.stages[running] = {"status": "running", "started": t, "warnings": [], "errors": []}
    if kind == "completed":
        stages_to(len(STAGE_ORDER)); p.state = "completed"; p.seconds = 52.0; p.coverage_pct = 100.0; p.started = t; p.ended = t
        write_part_files(job_dir, p, issues=[], coverage={"covered": 12, "applicable": 12, "percent": 100.0, "by_status": {"covered": 12}, "excluded": [], "note": "Diagnostic only."})
        p.material = {"name": "Generic steel (fixture)"}
    elif kind == "review":
        stages_to(len(STAGE_ORDER)); p.stages["verification"]["status"] = "warning"; p.stages["verification"]["warnings"] = ["2 issues need review"]
        p.state = "review_required"; p.review_status = "required"; p.seconds = 61.5; p.coverage_pct = 91.7; p.started = t; p.ended = t
        write_part_files(job_dir, p, issues=ISSUES, pages=2)
        p.issues = json.loads((job_dir / pid / "active" / "qa.json").read_text())["issues"]
    elif kind == "processing":
        stages_to(5, running=STAGE_ORDER[5]); p.state = STAGE_ORDER[5]; p.started = t
        write_part_files(job_dir, p, pdf=False, qa=False)
    elif kind == "stl_only":
        stages_to(3, running=STAGE_ORDER[3]); p.state = STAGE_ORDER[3]; p.started = t
        write_part_files(job_dir, p, pdf=False, qa=False)
    elif kind == "failed":
        stages_to(3); p.stages[STAGE_ORDER[3]] = {"status": "failed", "started": t, "ended": t, "warnings": [], "errors": ["RuntimeError: view layout does not fit the sheet"], "seconds": 1.0}
        p.state = "failed"; p.error = "RuntimeError: view layout does not fit the sheet"; p.started = t; p.ended = t; p.seconds = 12.0
        write_part_files(job_dir, p, pdf=False, qa=False)
    elif kind == "canceled":
        p.state = "canceled"; p.started = t; p.ended = t
    else:
        p.state = "queued"
    return p


def write_job(data_dir: Path, job_id: str, parts: list[tuple[str, str]], *, created="2026-11-25T10:00:00+00:00", sw=True, rejected=None) -> state.Job:
    """Persist a Job + its fixture artifacts under <data>/outputs/3d-to-2d/<job_id>/. ``parts`` is [(file name, kind)]."""
    store = state.JobStore(Path(data_dir) / "outputs" / "3d-to-2d")
    job = state.Job(job_id=job_id, template_id="solidflow-ansi-b", created=created, options={"rejected": rejected or []})
    if sw:
        job.solidworks = {"revision": "33.5.0", "major": 33, "service_pack": "SP5.0", "is_2025": True}
    jd = store.dir(job_id)
    job.parts = [make_part(job, n, k, jd) for n, k in parts]
    job.state = job.summary_state()
    store.save(job)
    store.event(job_id, "created", parts=len(job.parts))
    for p in job.parts:
        store.event(job_id, "stage_end", p.part_id, stage="preflight", status="succeeded")
    return job
